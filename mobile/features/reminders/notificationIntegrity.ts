/**
 * KitchenBuddy Stage 4A.1 — preview-first notification integrity recovery.
 *
 * This module does NOT rebuild the whole schedule, alter tracking indexes, or
 * repair ambiguous requests. Its one permitted repair is cancelling confirmed,
 * untracked v1 REGULAR expiry reminders which are obsolete relative to Pantry.
 *
 * IMPORTANT: Invoke manually after Pantry hydration and all schedulers settle.
 * The separate legacy repair remains MANUAL. Stage 4D automatic maintenance uses
 * assessHybridNotificationIntegrity and never calls the destructive legacy repair.
 */
import * as Notifications from "expo-notifications";
import AsyncStorage from "@react-native-async-storage/async-storage";
import { Platform } from "react-native";
import { usePantryStore } from "@/features/pantry/store";
import { ALL_CATEGORY_KEYS } from "@/features/pantry/constants";
import type { PantryItem } from "@/features/pantry/types";
import { EXPIRY_CATEGORY } from "./notificationContent";
import {
  analyzeNotificationSnapshot,
  type NotificationAudit,
} from "./notificationAudit";
import type { HybridPlan } from "./hybridExpiryPlanner";

type NativeRequest = Awaited<
  ReturnType<typeof Notifications.getAllScheduledNotificationsAsync>
>[number];

type RepairReason =
  | "replaced_by_v2"
  | "removed_from_pantry"
  | "outdated_expiry";
type ProtectedReason =
  | "legacy_follow_up"
  | "tracked_or_conflicting"
  | "not_proven_legacy_regular"
  | "no_safe_replacement";

export type LegacyRepairCandidate = {
  notificationId: string;
  pantryItemId: string;
  reason: RepairReason;
  /** Identifies the specific native request content used for the preview. */
  fingerprint: string;
};

export type IntegrityPreview = {
  checkedAt: number;
  audit: NotificationAudit;
  /** Only these exact native identifiers can be cancelled in this version. */
  eligible: LegacyRepairCandidate[];
  protectedLegacy: Record<ProtectedReason, number>;
  /** This is NOT a live scheduler lock; finish other scheduler work first. */
  readOnly: true;
};

const INDEX_KEYS = [
  "@kb_expiry_regular_index_v2",
  "@kb_expiry_snooze_index_v2",
  "water_notification_ids_v1",
  "expiry_notification_ids_v1",
] as const;

export const LEGACY_REPAIR_CONFIRMATION =
  "CANCEL_CONFIRMED_LEGACY_REGULAR_EXPIRY" as const;

function record(value: unknown): Record<string, unknown> | null {
  return value !== null && typeof value === "object" && !Array.isArray(value)
    ? (value as Record<string, unknown>)
    : null;
}

/**
 * Recognize both shipping generations of v1 regular expiry copy.
 * Oldest (pre-category): "Name expires soon" / "Name expires tomorrow."
 * Later v1: the editorial copy generated by expiryReminderCopy().
 * These comparisons are exact to avoid treating an unrelated expiry message as
 * one of our regular reminders. The caller independently checks the trigger,
 * Pantry evidence, lack of tracking and v2 marker.
 */
function legacyRegularLead(request: NativeRequest): number | null {
  const title = request.content.title;
  const body = request.content.body;
  if (typeof title !== "string" || typeof body !== "string") return null;

  const earliest = /^(.*?) expires soon$/.exec(title);
  if (
    earliest &&
    earliest[1].trim() &&
    body === `${earliest[1]} expires tomorrow.` &&
    request.content.categoryIdentifier == null
  )
    return 1;

  const dayBefore = /^(.*?) expires tomorrow$/.exec(title);
  if (
    dayBefore &&
    dayBefore[1].trim() &&
    body ===
      `A little kitchen heads-up: use ${dayBefore[1]} while it's fresh, or find a recipe for it.` &&
    request.content.categoryIdentifier === EXPIRY_CATEGORY
  )
    return 1;

  const planAhead = /^Plan ahead: (.+)$/.exec(title);
  if (planAhead && request.content.categoryIdentifier === EXPIRY_CATEGORY) {
    const days =
      /^(.*?) expires in ([23]) days\. There is still time to put it to good use\.$/.exec(
        body,
      );
    if (days && days[1] === planAhead[1]) return Number(days[2]);
  }
  return null;
}

/**
 * A date-only, non-repeating native trigger, on the expected LOCAL reminder
 * day, is additional independent evidence of a historical regular reminder.
 * The old Android format returned { type: 'date', value: epochMs, repeats:false }.
 * Unknown trigger formats are protected, not guessed at.
 */
function legacyTriggerMatches(
  request: NativeRequest,
  expiryDate: unknown,
  lead: number,
): boolean {
  if (typeof expiryDate !== "string") return false;
  const match = /^(\d{4})-(\d{2})-(\d{2})$/.exec(expiryDate);
  if (!match) return false;
  const year = Number(match[1]);
  const month = Number(match[2]);
  const day = Number(match[3]);
  const expiry = new Date(year, month - 1, day);
  if (
    expiry.getFullYear() !== year ||
    expiry.getMonth() !== month - 1 ||
    expiry.getDate() !== day
  )
    return false;
  const trigger = record(request.trigger);
  if (
    !trigger ||
    trigger.type !== "date" ||
    trigger.repeats === true ||
    typeof trigger.value !== "number" ||
    !Number.isFinite(trigger.value)
  )
    return false;
  const when = new Date(trigger.value);
  if (!Number.isFinite(when.getTime())) return false;
  expiry.setDate(expiry.getDate() - lead);
  return (
    when.getFullYear() === expiry.getFullYear() &&
    when.getMonth() === expiry.getMonth() &&
    when.getDate() === expiry.getDate()
  );
}

function isOldFollowUp(request: NativeRequest): boolean {
  const title = request.content.title;
  const body = request.content.body;
  return (
    (typeof title === "string" && title.startsWith("A follow-up for ")) ||
    (typeof body === "string" && body.startsWith("Your reminder is back."))
  );
}

function contentFingerprint(
  request: NativeRequest,
  reason: RepairReason,
): string {
  // Stable within a manual preview and a subsequent re-read. Never use this
  // as a security token, only as an exact native-request change detector.
  return JSON.stringify({
    id: request.identifier,
    title: request.content.title,
    body: request.content.body,
    category: request.content.categoryIdentifier,
    data: request.content.data,
    trigger: request.trigger,
    reason,
  });
}

function readHydratedPantry(): { reference: unknown; items: PantryItem[] } {
  const state = usePantryStore.getState();
  if (!state.hydrated || state.hydrationError) {
    throw new Error(
      "Pantry must be successfully hydrated before an integrity check.",
    );
  }
  const pantry = record(state.pantry);
  if (
    !pantry ||
    !ALL_CATEGORY_KEYS.every((key) => Array.isArray(pantry[key]))
  ) {
    throw new Error(
      "Pantry shape is invalid; refusing to plan notification deletions.",
    );
  }
  const items = ALL_CATEGORY_KEYS.flatMap((key) => pantry[key] as PantryItem[]);
  const ids = new Set<string>();
  for (const item of items) {
    if (!item || typeof item.id !== "string" || !item.id || ids.has(item.id)) {
      throw new Error(
        "Pantry contains an invalid/duplicate item ID; no repair is safe.",
      );
    }
    ids.add(item.id);
  }
  return { reference: state.pantry, items };
}

function sortCandidates(
  candidates: LegacyRepairCandidate[],
): LegacyRepairCandidate[] {
  return candidates.sort((a, b) =>
    a.notificationId.localeCompare(b.notificationId),
  );
}

/**
 * Inspection only. The Stage 4A audit is the authoritative index/OS comparison.
 * This adds Pantry-based evidence for safe v1 cleanup; it does not repair v2,
 * water, unknown, untracked-but-valid, or legacy follow-up requests.
 */
export async function checkNotificationIntegrity(): Promise<IntegrityPreview> {
  const pantry = readHydratedPantry();
  // Feed the exact same native/storage snapshot into Stage 4A's pure analyzer.
  const [native, pairs] = await Promise.all([
    Notifications.getAllScheduledNotificationsAsync(),
    AsyncStorage.multiGet([...INDEX_KEYS]),
  ]);
  const stored = Object.fromEntries(pairs) as Record<
    (typeof INDEX_KEYS)[number],
    string | null
  >;
  const audit = analyzeNotificationSnapshot(native, stored, Platform.OS);
  if (usePantryStore.getState().pantry !== pantry.reference) {
    throw new Error(
      "Pantry changed during integrity inspection. Retry after saving settles.",
    );
  }

  // Refuse repair if the snapshot indicates a scheduler may be in-flight.
  if (
    audit.tracking.missingFromOS ||
    audit.tracking.metadataMismatch ||
    audit.tracking.duplicateTrackedIds
  ) {
    throw new Error(
      "Native/index schedule is changing or inconsistent. Wait for sync and audit again.",
    );
  }
  const nativeIds = new Set(native.map((entry) => entry.identifier));
  if (nativeIds.size !== native.length) {
    throw new Error(
      "Native snapshot contains duplicate identifiers; no repair is safe.",
    );
  }
  const untracked = new Set(audit.diagnostics.untrackedKitchenBuddyIds);
  if ([...untracked].some((id) => !nativeIds.has(id))) {
    throw new Error(
      "Native pending requests changed between audit reads. Retry.",
    );
  }

  const items = new Map(pantry.items.map((item) => [item.id, item]));
  const v2ForItem = new Set<string>();
  for (const entry of native) {
    const data = record(entry.content.data);
    if (
      data?.type === "expiry_reminder" &&
      data.kbReminderKind === "regular" &&
      !untracked.has(entry.identifier) &&
      typeof data.pantryItemId === "string"
    ) {
      const current = items.get(data.pantryItemId);
      if (current && current.expiryDate === data.expiryDate) {
        v2ForItem.add(data.pantryItemId);
      }
    }
  }

  const eligible: LegacyRepairCandidate[] = [];
  const protectedLegacy: Record<ProtectedReason, number> = {
    legacy_follow_up: 0,
    tracked_or_conflicting: 0,
    not_proven_legacy_regular: 0,
    no_safe_replacement: 0,
  };
  for (const entry of native) {
    const data = record(entry.content.data);
    if (
      data?.type !== "expiry_reminder" ||
      data.kbReminderKind === "regular" ||
      data.kbReminderKind === "snooze" ||
      data.kbReminderKind === "group"
    )
      continue;
    // Only the v1 payload lacked the marker. A surprising new marker is not v1.
    if (data.kbReminderKind != null) {
      protectedLegacy.not_proven_legacy_regular++;
      continue;
    }
    if (!untracked.has(entry.identifier)) {
      protectedLegacy.tracked_or_conflicting++;
      continue;
    }
    if (isOldFollowUp(entry)) {
      protectedLegacy.legacy_follow_up++;
      continue;
    }
    const historicalLead = legacyRegularLead(entry);
    if (
      typeof data.pantryItemId !== "string" ||
      !data.pantryItemId ||
      historicalLead === null ||
      !legacyTriggerMatches(entry, data.expiryDate, historicalLead)
    ) {
      protectedLegacy.not_proven_legacy_regular++;
      continue;
    }
    const item = items.get(data.pantryItemId);
    let reason: RepairReason | null = null;
    if (!item) reason = "removed_from_pantry";
    else if (!item.expiryDate || item.expiryDate !== data.expiryDate)
      reason = "outdated_expiry";
    else if (v2ForItem.has(item.id)) reason = "replaced_by_v2";
    if (!reason) {
      protectedLegacy.no_safe_replacement++;
      continue;
    }
    eligible.push({
      notificationId: entry.identifier,
      pantryItemId: data.pantryItemId,
      reason,
      fingerprint: contentFingerprint(entry, reason),
    });
  }
  return {
    checkedAt: Date.now(),
    audit,
    eligible: sortCandidates(eligible),
    protectedLegacy,
    readOnly: true,
  };
}

/** Explicit, read-only preview: log counts but not IDs or ingredient names. */
export async function previewNotificationRepairs(): Promise<IntegrityPreview> {
  const preview = await checkNotificationIntegrity();
  if (__DEV__) {
    const reasons = preview.eligible.reduce<Record<RepairReason, number>>(
      (counts, item) => {
        counts[item.reason]++;
        return counts;
      },
      { replaced_by_v2: 0, removed_from_pantry: 0, outdated_expiry: 0 },
    );
    console.log(
      "[KB Notification Integrity] PREVIEW ONLY",
      JSON.stringify(
        {
          pending: preview.audit.pending.total,
          untracked: preview.audit.tracking.untrackedPending,
          eligible: preview.eligible.length,
          eligibleReasons: reasons,
          protectedLegacy: preview.protectedLegacy,
          noChangesMade: true,
        },
        null,
        2,
      ),
    );
  }
  return preview;
}

/**
 * Manual, preview-bound repair. Exact confirmation is required; the function
 * recomputes eligibility before each cancellation. Never auto-call at startup.
 * If another scheduler runs concurrently, abort and preview again.
 */
export async function repairNotificationIntegrity(
  approvedPreview: IntegrityPreview,
  confirmation: typeof LEGACY_REPAIR_CONFIRMATION,
): Promise<{
  cancelled: number;
  before: NotificationAudit;
  after: IntegrityPreview;
}> {
  if (confirmation !== LEGACY_REPAIR_CONFIRMATION) {
    throw new Error(
      "Explicit legacy-regular-expiry repair confirmation is required.",
    );
  }
  if (
    !approvedPreview ||
    approvedPreview.readOnly !== true ||
    !Array.isArray(approvedPreview.eligible)
  ) {
    throw new Error("A current integrity preview is required.");
  }
  const current = await checkNotificationIntegrity();
  const matches = (a: IntegrityPreview, b: IntegrityPreview) =>
    JSON.stringify(a.eligible) === JSON.stringify(b.eligible) &&
    a.audit.tracking.uniqueIds === b.audit.tracking.uniqueIds &&
    a.audit.pending.total === b.audit.pending.total &&
    a.audit.tracking.untrackedPending === b.audit.tracking.untrackedPending;
  if (!matches(approvedPreview, current)) {
    throw new Error(
      "Schedule changed since preview. Nothing cancelled; preview again.",
    );
  }
  let cancelled = 0;
  for (const candidate of approvedPreview.eligible) {
    // Re-evaluate the individual candidate against the CURRENT Pantry, tracking
    // indexes and native schedule just before cancelling its exact ID.
    const fresh = await checkNotificationIntegrity();
    const stillSafe = fresh.eligible.find(
      (entry) =>
        entry.notificationId === candidate.notificationId &&
        entry.fingerprint === candidate.fingerprint &&
        entry.reason === candidate.reason,
    );
    if (!stillSafe) {
      throw new Error(
        `Integrity repair stopped after ${cancelled} cancellation(s): schedule changed. Run a fresh audit.`,
      );
    }
    await Notifications.cancelScheduledNotificationAsync(
      candidate.notificationId,
    );
    cancelled++;
  }
  const after = await verifyNotificationIntegrity();
  if (__DEV__)
    console.log(
      "[KB Notification Integrity] REPAIR RESULT",
      JSON.stringify(
        {
          cancelled,
          beforePending: current.audit.pending.total,
          afterPending: after.audit.pending.total,
          remainingEligible: after.eligible.length,
          remainingUntracked: after.audit.tracking.untrackedPending,
        },
        null,
        2,
      ),
    );
  return { cancelled, before: current.audit, after };
}

/** A fresh read-only check of native occupancy and remaining discrepancies. */
export async function verifyNotificationIntegrity(): Promise<IntegrityPreview> {
  return checkNotificationIntegrity();
}

/**
 * Stage 4D — purely classify the completed native audit against the hybrid plan.
 * No OS calls, no permission prompts, no deletions or scheduling.
 * Water is checked for index/native agreement by the audit, not rebuilt here.
 */
export type HybridIntegrityAssessment = {
  healthy: boolean;
  expectedExpiry: {
    individual: number;
    groups: number;
    total: number;
    representedItems: number;
  };
  actualExpiry: { individual: number; groups: number; total: number };
  discrepancies: {
    countMismatch: boolean;
    missingFromOS: number;
    untrackedPending: number;
    metadataMismatch: number;
    duplicateTrackedIds: number;
    legacyExpiry: number;
    unknown: number;
  };
  warnings: string[];
};

export function assessHybridNotificationIntegrity(
  plan: HybridPlan,
  audit: NotificationAudit,
): HybridIntegrityAssessment {
  const expectedExpiry = {
    individual: plan.counts.individualNotifications,
    groups: plan.counts.groupNotifications,
    total: plan.counts.plannedNotifications,
    representedItems: plan.counts.representedItems,
  };
  const actualExpiry = {
    individual: audit.pending.regularExpiry,
    groups: audit.pending.groupExpiry,
    total: audit.pending.regularExpiry + audit.pending.groupExpiry,
  };
  const discrepancies = {
    countMismatch:
      expectedExpiry.individual !== actualExpiry.individual ||
      expectedExpiry.groups !== actualExpiry.groups ||
      expectedExpiry.total !== actualExpiry.total,
    missingFromOS: audit.tracking.missingFromOS,
    untrackedPending: audit.tracking.untrackedPending,
    metadataMismatch: audit.tracking.metadataMismatch,
    duplicateTrackedIds: audit.tracking.duplicateTrackedIds,
    legacyExpiry: audit.pending.legacyExpiry,
    unknown: audit.pending.unknown,
  };
  const warnings = [...audit.warnings];
  if (discrepancies.countMismatch) {
    warnings.push(
      "Actual individual/group expiry counts differ from the hybrid plan.",
    );
  }
  if (discrepancies.legacyExpiry) {
    warnings.push(
      "Legacy expiry requests need manual review; they are never auto-deleted.",
    );
  }
  return {
    healthy:
      !discrepancies.countMismatch &&
      !discrepancies.missingFromOS &&
      !discrepancies.untrackedPending &&
      !discrepancies.metadataMismatch &&
      !discrepancies.duplicateTrackedIds &&
      !discrepancies.legacyExpiry &&
      !discrepancies.unknown &&
      !audit.capacity.overBudget,
    expectedExpiry,
    actualExpiry,
    discrepancies,
    warnings,
  };
}
